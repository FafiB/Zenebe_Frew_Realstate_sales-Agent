create table if not exists public.properties (
  id bigint generated by default as identity primary key,
  title text not null,
  location text not null,
  price bigint not null check (price > 0),
  beds smallint not null default 0 check (beds >= 0),
  baths numeric(3, 1) not null default 0 check (baths >= 0),
  area integer not null default 0 check (area >= 0),
  property_type text not null check (property_type in ('Apartment', 'Shop')),
  status text not null default 'For sale' check (status in ('For sale', 'Under contract', 'Sold')),
  image_url text not null default '',
  video_url text not null default '',
  description text not null default '',
  featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inquiries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 120),
  email text not null check (char_length(email) between 3 and 254),
  phone text not null default '' check (char_length(phone) <= 40),
  message text not null check (char_length(btrim(message)) between 1 and 2000),
  property_id bigint references public.properties (id) on delete set null,
  created_at timestamptz not null default now(),
  contacted boolean not null default false
);

create index if not exists properties_public_order_idx
  on public.properties (status, featured desc, created_at desc);
create index if not exists inquiries_created_at_idx
  on public.inquiries (created_at desc);

create or replace function public.update_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists properties_set_updated_at on public.properties;
create trigger properties_set_updated_at
before update on public.properties
for each row execute function public.update_updated_at();

